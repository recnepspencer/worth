#[test]
fn canonical_encoders_reproduce_independent_checkpoint_literals() {
    let store_bytes = core::array::from_fn(|index| (index + 1) as u8);
    let store = StableStoreIdentity::from_published_record(
        ProposedStoreIdentity::from_nonzero_bytes(store_bytes).unwrap(),
    );
    let identity = PhysicalCheckpointIdentity::new(store, NonZeroU64::new(7).unwrap());
    let source = PhysicalCheckpointSource::concurrent(
        identity,
        CheckpointWalSourceRange::new(10, 20).unwrap(),
        CheckpointRootBasis::new(3, 4),
        5,
    );
    let dirty = CheckpointDirtyFrameBasis::new(
        RecordFrameCoordinate::new(RecordArtifactFile::BootstrapCatalog, 64, 16).unwrap(),
        6,
    );
    let (mut encoder, header) = CheckpointStreamEncoder::begin(source);
    let dirty_record = encoder.encode_dirty_basis(dirty);
    let compact = CheckpointBindingCompactionHeader::new(9, 18).unwrap();
    let (mut encoder, compaction) = encoder.begin_binding_compaction(compact);
    let binding = encoder.encode_binding_record(&[0xaa, 0xbb, 0xcc]).unwrap();
    let (_, footer) = encoder.finish();

    assert_eq!(header, HEADER);
    assert_eq!(dirty_record, DIRTY);
    assert_eq!(compaction, COMPACTION);
    assert_eq!(binding, BINDING);
    assert_eq!(footer, FOOTER);
}
