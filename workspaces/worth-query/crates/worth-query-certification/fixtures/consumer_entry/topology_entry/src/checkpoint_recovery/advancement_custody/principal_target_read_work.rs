//! Independent work quote for this fixture's principal-target traversal.
// One mapping seed reaches one principal through one relation in one partition.
// Bounds describe its declared records, never a measured request report.
const MAPPING_SEEDS: u64 = 1;
const RELATION_KINDS: u64 = 1;
const SELECTED_PARTITIONS: u64 = 1;
const MAPPING_ENTITIES: u64 = 1;
const PRINCIPAL_ENTITIES: u64 = 1;
const TARGET_RELATIONS: u64 = 1;
const ENTITY_RECORDS: u64 = MAPPING_ENTITIES + PRINCIPAL_ENTITIES;
const RECORDS: u64 = ENTITY_RECORDS + TARGET_RELATIONS;

const MAPPING_RECORD_BYTES: u64 = 819;
const PRINCIPAL_RECORD_BYTES: u64 = 601;
const TARGET_RELATION_BYTES: u64 = 257;
const RETAINED_FRAGMENT_BYTES: u64 = 2021;
const PAYLOAD_CHUNK_BYTES: u64 = 4096;
const VISIT_DIGEST_PAYLOAD_PASSES: u64 = 4;
const VISIT_DIGEST_FIXED_BYTES: u64 = 1024;
const DEDUPLICATION_KEY_PASSES: u64 = 2;

const fn chunks(bytes: u64) -> u64 {
    bytes.div_ceil(PAYLOAD_CHUNK_BYTES)
}
const fn visit_digest_work(record_bytes: u64) -> u64 {
    chunks(VISIT_DIGEST_PAYLOAD_PASSES * record_bytes + VISIT_DIGEST_FIXED_BYTES)
}

const SEED_COPY: u64 = MAPPING_SEEDS;
const SEED_ORDERING: u64 = MAPPING_SEEDS;
const KIND_COPY: u64 = RELATION_KINDS;
const KIND_ORDERING: u64 = RELATION_KINDS;
const PACKET_PAYLOAD_COPY: u64 = MAPPING_SEEDS + RELATION_KINDS;
const PREPARATION: u64 =
    SEED_COPY + SEED_ORDERING + KIND_COPY + KIND_ORDERING + PACKET_PAYLOAD_COPY;

const SEED_FRONTIER_VISITS: u64 = MAPPING_SEEDS;
const ENTITY_VISITS: u64 = ENTITY_RECORDS;
const RELATION_VISITS: u64 = TARGET_RELATIONS;
const TRAVERSAL: u64 = SEED_FRONTIER_VISITS + ENTITY_VISITS + RELATION_VISITS;

const PAYLOAD_BACKING_CLAIMS: u64 = chunks(RETAINED_FRAGMENT_BYTES);
const FRAGMENT_CLAIMS: u64 = SELECTED_PARTITIONS;
const VISIT_DIGESTS: u64 = visit_digest_work(MAPPING_RECORD_BYTES)
    + visit_digest_work(PRINCIPAL_RECORD_BYTES)
    + visit_digest_work(TARGET_RELATION_BYTES);
const RECORD_STAGING: u64 = RECORDS;
const DEDUPLICATION_KEYS: u64 = DEDUPLICATION_KEY_PASSES * RECORDS;
const FINAL_DIGESTS: u64 =
    chunks(MAPPING_RECORD_BYTES) + chunks(PRINCIPAL_RECORD_BYTES) + chunks(TARGET_RELATION_BYTES);
const COMPLETION: u64 = PAYLOAD_BACKING_CLAIMS
    + FRAGMENT_CLAIMS
    + VISIT_DIGESTS
    + RECORD_STAGING
    + DEDUPLICATION_KEYS
    + FINAL_DIGESTS;

pub(crate) const PRINCIPAL_TARGET_READ_WORK: u64 = PREPARATION + TRAVERSAL + COMPLETION;
