"""Exact callers of worth-query-execution's sealed test doors, for boundary-check's seal rule.

The seal rule lets a `*_for_test` / `*ForTest` name be referenced only by its owner and by
the files `tools/boundary-check/config/control-callers.txt` lists for that owner. Every court
or testkit file naming a control another crate declares (the library's doors and existing test
doors, a family testkit's controls, or a root crate's) gets an entry with that crate as owner.
An entry whose caller file no longer exists and lay in this crate family (the library or one
of its courts and testkits) is moved to the file's new home when exactly one moved file has the
same module path, and dropped otherwise. Every other entry is left as it is.
"""
import os
from pathlib import Path
import re

from rust_source import tokens

CONFIG = 'tools/boundary-check/config/control-callers.txt'
LEGACY_HEADER = '# Moved worth-query-execution courts and testkits reach the library only through its sealed doors, and testkit or root-crate controls only as listed.'
GENERATED_HEADER = '# Exact sealed-door callers generated by src_door_callers.py.'
OWNER = 'workspaces/worth-query/crates/worth-query-execution/'
CRATES = 'workspaces/worth-query/crates'
TEST_NAME = re.compile(r'^\w+(?:_for_test|ForTest)$')
DECLARING = ('fn', 'struct', 'enum', 'trait', 'type', 'const', 'static', 'mod', 'union', 'macro_rules')


def declared_in(directory):
    names = set()
    for path in sorted(Path(directory).rglob('*.rs')):
        stream = tokens(path.read_text(encoding='utf-8'))
        for i in range(len(stream) - 1):
            if stream[i].value in DECLARING and TEST_NAME.match(stream[i + 1].value):
                names.add(stream[i + 1].value)
            if stream[i].value == 'macro_rules' and i + 2 < len(stream) and TEST_NAME.match(stream[i + 2].value):
                names.add(stream[i + 2].value)
    return names


def declared_doors(root):
    return declared_in(root / OWNER / 'src')


def control_owners(root):
    """{control name: owner dirs}, retaining ambiguous names in distinct crates.

    An exact caller must name every possible external owner of a sealed control.
    A declaration in the caller's own crate resolves that name locally.
    """
    seen = {}
    crates = [root / OWNER] + [d for d in sorted((root / CRATES).iterdir())
                               if d.name.startswith('worth-query-testkit-') and 'execution' in d.name]
    if (root / 'crates').is_dir():
        crates += [d for d in sorted((root / 'crates').iterdir()) if (d / 'src').is_dir()]
    for directory in crates:
        for name in declared_in(directory / 'src'):
            seen.setdefault(name, set()).add(directory.relative_to(root).as_posix() + '/')
    return seen


def moved_files(root):
    crates = root / CRATES
    return sorted(f for d in sorted(crates.iterdir())
                  if d.name.startswith(('worth-query-court-', 'worth-query-testkit-')) and 'execution' in d.name
                  for f in d.rglob('*.rs'))


def in_family(path):
    name = path.split('/')[3] if path.startswith(CRATES + '/') and path.count('/') > 3 else ''
    return name == 'worth-query-execution' or (
        name.startswith(('worth-query-court-', 'worth-query-testkit-')) and 'execution' in name)


def module_key(path):
    tail = path.split('/domain_computation/', 1)
    return 'domain_computation/' + tail[1] if len(tail) == 2 else None


def updated(root, lines, callers=()):
    """New control-callers lines: stale callers moved or dropped, door callers added."""
    files = sorted(set(callers)) if callers else moved_files(root)
    by_key = {}
    for f in files:
        rel = f.relative_to(root).as_posix()
        by_key.setdefault(module_key(rel), []).append(rel)
    out, present = [], set()
    for line in lines:
        parts = line.split()
        if line == LEGACY_HEADER:
            continue
        if line == GENERATED_HEADER and line in out:
            continue
        if len(parts) == 2 and not line.startswith('#') and tuple(parts) in present:
            continue
        if len(parts) != 2 or line.startswith('#') or (root / parts[1]).exists() or not in_family(parts[1]):
            out.append(line)
            present.add(tuple(parts))
            continue
        candidates = by_key.get(module_key(parts[1]), [])
        if len(candidates) == 1:
            entry = (parts[0], candidates[0])
            if entry not in present:
                out.append(' '.join(entry))
                present.add(entry)
    added = []
    owners = control_owners(root)
    for f in files:
        rel = f.relative_to(root).as_posix()
        own = '/'.join(rel.split('/')[:4]) + '/'
        names = {t.value for t in tokens(f.read_text(encoding='utf-8')) if t.kind == 'ident'}
        reached = set().union(*(owners[n] for n in names if n in owners and own not in owners[n]))
        for owner in sorted(reached - {own}):
            if (owner, rel) not in present:
                added.append(f'{owner} {rel}')
                present.add((owner, rel))
    if added:
        if GENERATED_HEADER not in out:
            out.append(GENERATED_HEADER)
        out.extend(sorted(added))
    return out


def update_callers(root, callers=()):
    path = root / CONFIG
    lines = path.read_text(encoding='utf-8').splitlines()
    new = updated(root, lines, callers)
    path.write_text('\n'.join(new) + '\n', encoding='utf-8', newline='\n')
    return len(new) - len(lines)


CERTIFICATION = 'tools/boundary-check/config/certification-construction-callers.txt'
FACTORIES = {'installation': {'certification_query'}}


def relocated_caller(root, files, kind, stale):
    """The one moved file a stale closed-list caller became: same module path, or, failing that,
    the one with the same trailing path that still names the class's factory."""
    stem = re.sub(r'(\.rs|/mod\.rs)$', '', module_key(stale) or '')
    names = FACTORIES.get(kind, set())

    def reads(rel):
        return bool(names & {t.value for t in tokens((root / rel).read_text(encoding='utf-8'))})
    same = [f for f in files if re.sub(r'(\.rs|/mod\.rs)$', '', module_key(f) or '') == stem]
    if len(same) > 1:
        same = [f for f in same if reads(f)]
    if len(same) == 1:
        return same[0]
    tail = '/'.join(stem.split('/')[-2:])
    near = [f for f in files if re.sub(r'(\.rs|/mod\.rs)$', '', f).endswith('/' + tail) and reads(f)]
    return near[0] if len(near) == 1 else None


def relocate_certification_callers(root):
    """Move closed certification-construction callers the move relocated, and give a registered
    caller's child module files that name the factory the same entry; returns lines written."""
    path = root / CERTIFICATION
    files = [f.relative_to(root).as_posix() for f in moved_files(root)]
    out, moved = [], 0
    for line in path.read_text(encoding='utf-8').splitlines():
        parts = line.split()
        if len(parts) == 2 and not line.startswith('#') and not (root / parts[1]).exists() and in_family(parts[1]):
            target = relocated_caller(root, files, parts[0], parts[1])
            if target is not None:
                line, moved = f'{parts[0]} {target}', moved + 1
        out.append(line)
    # A registered caller split into child files stays one caller: each child module file inside
    # its module directory that names the class's factory gets the same entry, beside it.
    registered = [(i, line.split()) for i, line in enumerate(out) if len(line.split()) == 2 and not line.startswith('#')]
    present = {tuple(parts) for _, parts in registered}
    for index, (kind, caller) in reversed(registered):
        directory = re.sub(r'(/mod)?\.rs$', '', caller) + '/'
        names = FACTORIES.get(kind, set())
        children = sorted(f for f in files if f.startswith(directory) and (kind, f) not in present
                          and names & {t.value for t in tokens((root / f).read_text(encoding='utf-8'))})
        for child in reversed(children):
            out.insert(index + 1, f'{kind} {child}')
            present.add((kind, child))
            moved += 1
    path.write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    return moved


ROAD = 'tools/boundary-check/config/road1.toml'
MOVED_NOTE = '  # Moved worth-query-execution tests, exempt inside the library before the move:'


def relocate_denial_exclusions(root):
    """Identifier denials in road1.toml whose exclusions named library test files, or the whole
    library source, follow the moved tests: a stale exact path moves to the moved file(s) of the
    same module that name the identifier; a library-wide exclusion gains the exact moved files
    that name it. Returns the number of exclusion lines written."""
    path = root / ROAD
    lines = path.read_text(encoding='utf-8').split('\n')
    files = [f.relative_to(root).as_posix() for f in moved_files(root)]
    idents = {f: {t.value for t in tokens((root / f).read_text(encoding='utf-8')) if t.kind == 'ident'} for f in files}
    out, written, block = [], 0, None
    for i, line in enumerate(lines):
        if line.startswith('[[source_identifier_denials]]'):
            j = i + 1
            while j < len(lines) and not lines[j].startswith('forbidden_identifiers'):
                j += 1
            block = set(re.findall(r'"(\w+)"', lines[j])) if j < len(lines) else set()
        quoted = re.fullmatch(r'\s*"([^"]+)",', line)
        if block and quoted and line != MOVED_NOTE:
            entry = quoted.group(1)
            readers = sorted(f for f in files if block & idents[f])
            if entry == OWNER + 'src' and readers and MOVED_NOTE not in lines:
                out.append(line)
                out.append(MOVED_NOTE)
                out.extend(f'  "{f}",' for f in readers)
                written += len(readers)
                continue
            if not (root / entry).exists() and in_family(entry):
                stem = re.sub(r'(\.rs|/mod\.rs)$', '', module_key(entry) or '')
                same = [f for f in readers if re.sub(r'(\.rs|/mod\.rs)$', '', module_key(f) or '') == stem]
                if same:
                    out.extend(f'  "{f}",' for f in same)
                    written += len(same)
                    continue
        out.append(line)
    path.write_text('\n'.join(out), encoding='utf-8', newline='\n')
    return written


DOCS = ('docs/build-an-application.md', 'docs/how-it-works.md',
        'workspaces/worth-query/crates/worth-query/docs/foundations/invariants-and-read-observations.md',
        'workspaces/worth-query/crates/worth-query/docs/modeling/relation-laws.md')
LINK = re.compile(r'\]\(([^)\s#]*worth-query-execution/src/[^)\s#]+)(#[^)\s]*)?\)')


def relocate_doc_links(root):
    """Relative doc links to library test files the move relocated point at the moved file of the
    same module; a module split between a court and testkits links to its one court half."""
    files = [f.relative_to(root).as_posix() for f in moved_files(root)]
    by_stem = {}
    for f in files:
        by_stem.setdefault(re.sub(r'(\.rs|/mod\.rs)$', '', module_key(f) or ''), []).append(f)
    count = 0
    for doc in DOCS:
        path = root / doc
        if not path.exists():
            continue
        text = path.read_text(encoding='utf-8')

        def moved(match):
            nonlocal count
            target = (path.parent / match.group(1)).resolve()
            if target.exists():
                return match.group(0)
            stem = re.sub(r'(\.rs|/mod\.rs)$', '', module_key(target.as_posix()) or '')
            found = by_stem.get(stem, [])
            if len(found) > 1:  # split between a court (the tests) and testkits (support)
                found = [f for f in found if f.split('/')[3].startswith('worth-query-court-')]
            if len(found) != 1:
                return match.group(0)
            count += 1
            rel = Path(os.path.relpath(root / found[0], path.parent)).as_posix()
            return f']({rel}{match.group(2) or ""})'
        new = LINK.sub(moved, text)
        if new != text:
            path.write_text(new, encoding='utf-8', newline='\n')
    return count
